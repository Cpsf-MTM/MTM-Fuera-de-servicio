// Lista única de fabricantes ordenada
export function getFabricantesList(): string[] {
  const items = getStoredCatalogItems();
  const set = new Set<string>();
  items.forEach(i => {
    if (i.fabricante && i.fabricante.trim()) {
      set.add(i.fabricante.trim().toUpperCase());
    }
  });

  // Extra fabricantes agregados manualmente
  try {
    const extra = localStorage.getItem(STORAGE_KEY_EXTRA_FABRICANTES);
    if (extra) {
      const parsed: string[] = JSON.parse(extra);
      parsed.forEach(f => set.add(f.trim().toUpperCase()));
    }
  } catch (e) {
    // Ignore
  }

  return Array.from(set).sort((a, b) => a.localeCompare(b));
}

