// Parse base CSV to array
function parseDefaultCSV(): MachineCatalogItem[] {
  const items: MachineCatalogItem[] = [];
  const lines = RAW_MACHINE_CSV.trim().split('\n');
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(';');
    if (parts.length >= 6) {
      const numero = parts[0].trim();
      const isla = parts[1].trim();
      const etapa = parts[2].trim() || 'HABILITADA';
      const fabricante = parts[3].trim() || 'SIN ESPECIFICAR';
      const modelo = parts[4].trim() || '-';
      const gabinete = parts[5].trim() || '-';
      
      if (numero && !numero.includes('[') && !items.some(x => x.numero === numero)) {
        items.push({ numero, isla, etapa, fabricante, modelo, gabinete });
      }
    }
  }
  return items;
}

// In-memory working cache
let cachedCatalogItems: MachineCatalogItem[] | null = null;

// Cargar catálogo (LocalStorage o CSV Inicial)
export function getStoredCatalogItems(): MachineCatalogItem[] {
  if (cachedCatalogItems) {
    return cachedCatalogItems;
  }

  try {
    const stored = localStorage.getItem(STORAGE_KEY_CATALOG);
    if (stored) {
      const parsed: MachineCatalogItem[] = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        cachedCatalogItems = parsed;
        return parsed;
      }
    }
  } catch (e) {
    console.error('Error loading custom catalog from localStorage:', e);
  }

  const defaultItems = parseDefaultCSV();
  cachedCatalogItems = defaultItems;
  return defaultItems;
}

// Guardar catálogo en localStorage y notificar a toda la app
export function saveCatalogItems(items: MachineCatalogItem[]): void {
  cachedCatalogItems = items;
  try {
    localStorage.setItem(STORAGE_KEY_CATALOG, JSON.stringify(items));
    window.dispatchEvent(new CustomEvent('casino_catalog_updated'));
  } catch (e) {
    console.error('Error saving catalog to localStorage:', e);
  }
}

// Obtener mapa rápido por número de máquina
export function getMachineCatalog(): Record<string, MachineCatalogItem> {
  const items = getStoredCatalogItems();
  const map: Record<string, MachineCatalogItem> = {};
  items.forEach(item => {
    map[item.numero] = item;
  });
  return map;
}

