// Importar catálogo desde texto CSV
export function importCatalogFromCSV(csvText: string): { success: boolean; count: number; error?: string } {
  try {
    const lines = csvText.trim().split('\n');
    if (lines.length < 2) {
      return { success: false, count: 0, error: 'El archivo CSV está vacío o no contiene datos válidos' };
    }

    const items: MachineCatalogItem[] = [];
    const seen = new Set<string>();

    for (let i = 1; i < lines.length; i++) {
      const line = lines[i].trim();
      if (!line) continue;
      // Soportar punto y coma (;) o coma (,)
      const separator = line.includes(';') ? ';' : ',';
      const parts = line.split(separator);
      if (parts.length >= 2) {
        const numero = parts[0]?.trim() || '';
        const isla = parts[1]?.trim() || '-';
        const etapa = parts[2]?.trim() || 'HABILITADA';
        const fabricante = parts[3]?.trim() || 'SIN ESPECIFICAR';
        const modelo = parts[4]?.trim() || '-';
        const gabinete = parts[5]?.trim() || '-';

        if (numero && !seen.has(numero)) {
          seen.add(numero);
          items.push({ numero, isla, etapa, fabricante, modelo, gabinete });
        }
      }
    }

    if (items.length === 0) {
      return { success: false, count: 0, error: 'No se pudieron extraer máquinas válidas del archivo' };
    }

    saveCatalogItems(items);
    return { success: true, count: items.length };
  } catch (e: any) {
    return { success: false, count: 0, error: e?.message || 'Error al procesar el archivo CSV' };
  }
}

export interface OutOfServiceDuration {
  totalHours: number;
  totalDays: number;
  label: string;
  badgeType: 'recent' | 'moderate' | 'critical'; // recent (<24h), moderate (1-3d), critical (>3d)
}

export function calculateOutOfServiceDuration(fechaEgreso?: string): OutOfServiceDuration {
  if (!fechaEgreso) {
    return {
      totalHours: 0,
      totalDays: 0,
      label: 'S/D',
      badgeType: 'recent'
    };
  }

  const egresoTime = new Date(fechaEgreso).getTime();
  const now = new Date().getTime();
  const diffMs = Math.max(0, now - egresoTime);
  const totalHours = diffMs / (1000 * 60 * 60);
  const totalDays = Math.floor(totalHours / 24);

  let label = '';
  let badgeType: 'recent' | 'moderate' | 'critical' = 'recent';

  if (totalHours < 1) {
    const mins = Math.max(1, Math.round(diffMs / (1000 * 60)));
    label = `${mins} min`;
    badgeType = 'recent';
  } else if (totalHours < 24) {
    const hs = Math.floor(totalHours);
    label = `${hs} hs`;
    badgeType = 'recent';
  } else if (totalDays === 1) {
    label = `1 día`;
    badgeType = 'moderate';
  } else if (totalDays <= 3) {
    label = `${totalDays} días`;
    badgeType = 'moderate';
  } else {
    label = `${totalDays} días`;
    badgeType = 'critical';
  }

  return {
    totalHours,
    totalDays,
    label,
    badgeType
  };
}
