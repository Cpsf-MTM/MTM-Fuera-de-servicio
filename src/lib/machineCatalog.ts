// Agregar nueva máquina
export function addMachineToCatalog(item: MachineCatalogItem): { success: boolean; error?: string } {
  const current = getStoredCatalogItems();
  if (current.some(m => m.numero.trim() === item.numero.trim())) {
    return { success: false, error: `Ya existe una máquina registrada con el número ${item.numero}` };
  }
  const updated = [item, ...current];
  saveCatalogItems(updated);
  return { success: true };
}

// Actualizar máquina existente
export function updateMachineInCatalog(numero: string, updatedData: Partial<MachineCatalogItem>): { success: boolean; error?: string } {
  const current = getStoredCatalogItems();
  const idx = current.findIndex(m => m.numero.trim() === numero.trim());
  if (idx === -1) {
    return { success: false, error: `No se encontró la máquina ${numero}` };
  }
  const updated = [...current];
  updated[idx] = { ...updated[idx], ...updatedData };
  saveCatalogItems(updated);
  return { success: true };
}

// Dar de baja o retirar máquina (cambiar etapa a RETIRADA)
export function retireMachineFromCatalog(numero: string, reason?: string): { success: boolean; error?: string } {
  const current = getMachineDetails(numero);
  return updateMachineInCatalog(numero, { 
    etapa: 'RETIRADA',
    gabinete: reason ? `${current?.gabinete || ''} [Baja: ${reason}]`.trim() : current?.gabinete
  });
}

// Eliminar definitivamente del catálogo
export function deleteMachineFromCatalog(numero: string): { success: boolean; error?: string } {
  const current = getStoredCatalogItems();
  const filtered = current.filter(m => m.numero.trim() !== numero.trim());
  if (filtered.length === current.length) {
    return { success: false, error: `No se encontró la máquina ${numero}` };
  }
  saveCatalogItems(filtered);
  return { success: true };
}

