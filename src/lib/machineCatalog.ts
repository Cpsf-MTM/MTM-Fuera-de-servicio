// Renombrar fabricante en todo el parque
export function renameFabricanteInCatalog(oldName: string, newName: string): void {
  const cleanOld = oldName.trim().toUpperCase();
  const cleanNew = newName.trim().toUpperCase();
  if (!cleanNew || cleanOld === cleanNew) return;

  const current = getStoredCatalogItems();
  const updated = current.map(item => {
    if (item.fabricante.trim().toUpperCase() === cleanOld) {
      return { ...item, fabricante: cleanNew };
    }
    return item;
  });
  saveCatalogItems(updated);
}

// Exportar catálogo completo a formato CSV descargable
